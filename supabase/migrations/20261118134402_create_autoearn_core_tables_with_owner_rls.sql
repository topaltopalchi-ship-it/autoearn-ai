create table public.opportunities (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 160),
  platform text not null check (char_length(platform) between 2 and 100),
  url text not null,
  category text not null default 'game',
  reward_description text not null default '',
  eligibility text not null default '',
  terms_url text not null default '',
  status text not null default 'discovered'
    check (status in ('discovered','reviewing','eligible','ineligible','archived')),
  score integer not null default 0 check (score between 0 and 100),
  notes text not null default '',
  created_at timestamptz not null default now(),
  unique (owner_id, url)
);

create table public.tasks (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  opportunity_id bigint not null references public.opportunities(id) on delete cascade,
  description text not null check (char_length(description) between 3 and 500),
  status text not null default 'pending_approval'
    check (status in ('pending_approval','approved','completed','cancelled')),
  approved_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.rewards (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  opportunity_id bigint references public.opportunities(id) on delete set null,
  amount numeric(14,2) not null check (amount >= 0),
  currency text not null default 'USD' check (char_length(currency) between 3 and 8),
  status text not null default 'pending'
    check (status in ('pending','confirmed','paid','rejected')),
  reference text not null default '',
  created_at timestamptz not null default now()
);

create index opportunities_owner_created_idx on public.opportunities(owner_id, created_at desc);
create index opportunities_owner_status_idx on public.opportunities(owner_id, status);
create index tasks_owner_created_idx on public.tasks(owner_id, created_at desc);
create index tasks_opportunity_idx on public.tasks(opportunity_id);
create index rewards_owner_created_idx on public.rewards(owner_id, created_at desc);
create index rewards_opportunity_idx on public.rewards(opportunity_id);

alter table public.opportunities enable row level security;
alter table public.tasks enable row level security;
alter table public.rewards enable row level security;

revoke all on table public.opportunities, public.tasks, public.rewards from anon, authenticated;
grant select, insert, update, delete on table public.opportunities, public.tasks, public.rewards to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "owner manages opportunities"
on public.opportunities for all to authenticated
using ((select auth.uid()) = owner_id)
with check ((select auth.uid()) = owner_id);

create policy "owner manages tasks"
on public.tasks for all to authenticated
using ((select auth.uid()) = owner_id)
with check (
  (select auth.uid()) = owner_id
  and exists (
    select 1 from public.opportunities o
    where o.id = opportunity_id and o.owner_id = (select auth.uid())
  )
);

create policy "owner manages rewards"
on public.rewards for all to authenticated
using ((select auth.uid()) = owner_id)
with check (
  (select auth.uid()) = owner_id
  and (
    opportunity_id is null
    or exists (
      select 1 from public.opportunities o
      where o.id = opportunity_id and o.owner_id = (select auth.uid())
    )
  )
);
